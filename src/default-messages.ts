/**
 * 两批交错混排再去重。用户第二批自身有两条重复（"老铁，出来透气🌬️"、
 * "兄弟，出来整两句💬" 各出现两次），保留首次出现；两批之间无重复。
 * 空串不会进池（BATCH_2 较短时 flatMap 补的位），pool 实际 198 条。
 */
export const DEFAULT_MESSAGES: readonly string[] = interleaveDedup(BATCH_1, BATCH_2)

function interleaveDedup(batch1: readonly string[], batch2: readonly string[]): string[] {
  const seen = new Set<string>()
  const out: string[] = []
  for (const text of batch1.flatMap((t, i) => [t, batch2[i] ?? ""])) {
    if (text.length === 0 || seen.has(text)) continue
    seen.add(text)
    out.push(text)
  }
  return out
}
